// Extracts eLamX's bundled material catalogue from the Java original.
//
// `MaterialDataBase.getMaterials()` is 780 lines of generated setter calls -
// it was itself produced by `MaterialExcelTableReader`, which prints Java
// source from a spreadsheet. So the catalogue has already been through one
// machine translation, and re-typing it by hand for the port would be the only
// step in the chain a human touched. This script is the second machine step.
//
// Run it after changing the Java, and commit the output:
//
//     node web/scripts/generate-material-catalog.mjs
//
// It refuses rather than guesses: a material missing any of the 21 properties,
// or an unknown `type` constant, stops the run. The count is asserted too, so
// a parse that silently matched half the file cannot pass.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(
  HERE,
  "../../eLamX2/MaterialDatabase/src/de/elamx/materialdb/MaterialDataBase.java",
);
const TARGET = join(HERE, "../src/lib/materialCatalog.ts");

/** Java setter -> the field it fills, and whether it is a number. */
const NUMBERS = {
  setEpar: "e_par",
  setEnor: "e_nor",
  setNue12: "nue12",
  setG: "g",
  setRho: "rho",
  setAlphaTPar: "alpha_t_par",
  setAlphaTNor: "alpha_t_nor",
  setBetaPar: "beta_par",
  setBetaNor: "beta_nor",
  setRParTen: "r_par_ten",
  setRParCom: "r_par_com",
  setRNorTen: "r_nor_ten",
  setRNorCom: "r_nor_com",
  setRShear: "r_shear",
};
const STRINGS = {
  setName: "name",
  setFibreType: "fibreType",
  setFibreName: "fibreName",
  setMatrixType: "matrixType",
  setMatrixName: "matrixName",
};
// eLamX's own constants, from ExtendedDefaultMaterial.
const KINDS = {
  "ExtendedDefaultMaterial.TYPE_UNKNOWN": "unknown",
  "ExtendedDefaultMaterial.TYPE_UD": "ud",
  "ExtendedDefaultMaterial.TYPE_FABRIC": "fabric",
  "ExtendedDefaultMaterial.TYPE_GELEGE": "ncf",
};

const java = readFileSync(SOURCE, "utf8");

const entries = new Map();
// The argument is matched to the end of its own line, not to the first
// closing paren: a name like "C-'(HM)' | EP-'-'" has one inside the string.
const call = /^\s*materials\[(\d+)\]\.(set\w+)\((.*)\);\s*$/gm;
for (const [, index, setter, raw] of java.matchAll(call)) {
  const material = entries.get(index) ?? {};
  entries.set(index, material);

  if (setter in NUMBERS) {
    const value = Number(raw);
    if (!Number.isFinite(value)) throw new Error(`${setter}(${raw}) ist keine Zahl`);
    material[NUMBERS[setter]] = value;
  } else if (setter in STRINGS) {
    const text = raw.trim();
    if (!text.startsWith('"') || !text.endsWith('"')) {
      throw new Error(`${setter}(${raw}) ist kein String-Literal`);
    }
    material[STRINGS[setter]] = JSON.parse(text);
  } else if (setter === "setPhi") {
    material.phi = Number(raw);
  } else if (setter === "setType") {
    const kind = KINDS[raw.trim()];
    if (!kind) throw new Error(`unbekannte Materialart ${raw}`);
    material.kind = kind;
  } else {
    throw new Error(`unbekannter Setter ${setter} - Katalogfeld dazugekommen?`);
  }
}

const EXPECTED = 33;
if (entries.size !== EXPECTED) {
  throw new Error(`${entries.size} Materialien gefunden, ${EXPECTED} erwartet`);
}

const REQUIRED = [
  ...Object.values(NUMBERS),
  ...Object.values(STRINGS),
  "phi",
  "kind",
];

const materials = [...entries.entries()]
  .sort((a, b) => Number(a[0]) - Number(b[0]))
  .map(([index, m]) => {
    for (const field of REQUIRED) {
      if (m[field] === undefined) throw new Error(`Material ${index}: ${field} fehlt`);
    }
    return m;
  });

// Java prints doubles at full precision, which is where values like
// 1.6000000000000003E-9 come from. They are written out as JavaScript renders
// the same double - a different spelling of the identical number. Rounding
// here would be a second opinion, and this is a transcription.
const num = (v) => String(v);

const body = materials
  .map(
    (m) => `  {
    name: ${JSON.stringify(m.name)},
    fibreType: ${JSON.stringify(m.fibreType)},
    fibreName: ${JSON.stringify(m.fibreName)},
    matrixType: ${JSON.stringify(m.matrixType)},
    matrixName: ${JSON.stringify(m.matrixName)},
    phi: ${num(m.phi)},
    kind: ${JSON.stringify(m.kind)},
    properties: {
${Object.values(NUMBERS)
  .map((field) => `      ${field}: ${num(m[field])},`)
  .join("\n")}
    },
  },`,
  )
  .join("\n");

const out = `// GENERATED by web/scripts/generate-material-catalog.mjs from
// eLamX2/MaterialDatabase/src/de/elamx/materialdb/MaterialDataBase.java.
// Do not edit by hand - see the script for why it exists.
//
// eLamX's bundled catalogue: ${materials.length} plies from the literature, each named
// after its fibre and matrix. The numbers are transcribed exactly, full
// floating-point noise included, so a value here can be diffed against the
// original line for line.
//
// Units are the app's own throughout, which are also the original's: MPa for
// the moduli and strengths, 1/K for the expansion coefficients, t/mm^3 for the
// density.

/** How the reinforcement is laid up, from ExtendedDefaultMaterial's constants. */
export type CatalogKind = "ud" | "fabric" | "ncf" | "unknown";

export interface CatalogMaterial {
  /** eLamX's own name, built as \`fibreType-'fibreName' | matrixType-'matrixName'\`. */
  name: string;
  fibreType: string;
  fibreName: string;
  matrixType: string;
  matrixName: string;
  /** Fibre volume fraction in percent. Zero where the source gave none. */
  phi: number;
  kind: CatalogKind;
  /** The ply properties, under the names the app's own Material uses. */
  properties: {
    e_par: number;
    e_nor: number;
    nue12: number;
    g: number;
    rho: number;
    alpha_t_par: number;
    alpha_t_nor: number;
    beta_par: number;
    beta_nor: number;
    r_par_ten: number;
    r_par_com: number;
    r_nor_ten: number;
    r_nor_com: number;
    r_shear: number;
  };
}

export const MATERIAL_CATALOG: CatalogMaterial[] = [
${body}
];
`;

writeFileSync(TARGET, out);
console.log(`materialCatalog.ts geschrieben: ${materials.length} Materialien`);
